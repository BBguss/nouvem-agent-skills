#!/usr/bin/env node
// Rewrite the skill index in README.md (between <!-- skill-index:begin --> and
// <!-- skill-index:end -->) from each skill's SKILL.md frontmatter.
// Group: frontmatter `category:` if present, else the GROUPS map below, else "Other".
// Usage: node scripts/gen-index.mjs [--check]   (--check exits 1 when README is out of date)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const PACK = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const README = path.join(PACK, 'README.md');
const BEGIN = '<!-- skill-index:begin -->';
const END = '<!-- skill-index:end -->';

const ORDER = ['Build & develop', 'Analyze & plan', 'Orchestration', 'Ship & operate', 'Security & agent safety', 'Web quality', 'Other'];
const GROUPS = {
  'build-project': 'Build & develop',
  'code-change': 'Build & develop',
  'local-dev-setup': 'Build & develop',
  'plan-then-code': 'Build & develop',
  'agent-tool-parity': 'Build & develop',
  'honest-errors': 'Build & develop',
  'real-ui-verify': 'Build & develop',
  'analyze-problem': 'Analyze & plan',
  'error-runbook': 'Analyze & plan',
  'mode-gates': 'Analyze & plan',
  'external-project-scope': 'Analyze & plan',
  'dynamic-workflow': 'Orchestration',
  'task-delegation': 'Orchestration',
  'definition-of-done': 'Orchestration',
  'living-docs': 'Orchestration',
  'release-deploy': 'Ship & operate',
  'safe-hotfix': 'Ship & operate',
  'prod-log-watch': 'Ship & operate',
  'maintenance-window-ops': 'Ship & operate',
  'zero-downtime-migration': 'Ship & operate',
  'remote-offload': 'Ship & operate',
  'desktop-release': 'Ship & operate',
  'data-migration': 'Ship & operate',
  'security-audit-cycle': 'Security & agent safety',
  'credential-broker': 'Security & agent safety',
  'hitl-approvals': 'Security & agent safety',
  'agent-safety-hooks': 'Security & agent safety',
  'web-quality-audit': 'Web quality',
};

function frontmatter(file) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---/.exec(fs.readFileSync(file, 'utf8'));
  const out = {};
  if (m) for (const line of m[1].split(/\r?\n/)) {
    const kv = /^([A-Za-z_-]+):\s*(.*)$/.exec(line);
    if (kv) out[kv[1]] = kv[2].replace(/^["']|["']$/g, '').trim();
  }
  return out;
}

function summary(desc) {
  let s = desc.replace(/^Use (it )?(at|in|when|whenever)\s+/i, '').split(/(?<=\.)\s/)[0].replace(/\.$/, '');
  if (s.length > 170) s = s.slice(0, 167).replace(/\s+\S*$/, '') + '...';
  return s.charAt(0).toUpperCase() + s.slice(1);
}

const skills = fs.readdirSync(PACK, { withFileTypes: true })
  .filter((e) => (e.isDirectory() || e.isSymbolicLink()) && !/^[._]/.test(e.name) && fs.existsSync(path.join(PACK, e.name, 'SKILL.md')))
  .map((e) => {
    const fm = frontmatter(path.join(PACK, e.name, 'SKILL.md'));
    const name = fm.name || e.name;
    let slash = [];
    try { slash = JSON.parse(fs.readFileSync(path.join(PACK, e.name, 'triggers.json'), 'utf8')).slash || []; } catch { /* none */ }
    return { dir: e.name, name, group: fm.category || GROUPS[name] || 'Other', when: summary(fm.description || ''), slash };
  });

const lines = [`${skills.length} skills. Generated by \`node scripts/gen-index.mjs\` from each SKILL.md; do not edit by hand.`, ''];
for (const g of ORDER.concat([...new Set(skills.map((s) => s.group))].filter((g) => !ORDER.includes(g)))) {
  const list = skills.filter((s) => s.group === g).sort((a, b) => a.name.localeCompare(b.name));
  if (!list.length) continue;
  lines.push(`### ${g}`, '', '| Skill | Use it when | Aliases |', '|---|---|---|');
  for (const s of list) {
    lines.push(`| [\`${s.name}\`](${s.dir}/SKILL.md) | ${s.when.replace(/\|/g, '\\|')} | ${s.slash.map((x) => '`' + x + '`').join(' ')} |`);
  }
  lines.push('');
}
const block = `${BEGIN}\n${lines.join('\n').trim()}\n${END}`;

const cur = fs.readFileSync(README, 'utf8');
const b = cur.indexOf(BEGIN), e = cur.indexOf(END);
if (b < 0 || e < b) { console.error(`README.md has no ${BEGIN} ... ${END} section`); process.exit(1); }
const next = cur.slice(0, b) + block + cur.slice(e + END.length);
if (process.argv.includes('--check')) {
  if (next !== cur) { console.error('README skill index is out of date: run node scripts/gen-index.mjs'); process.exit(1); }
  console.log('README skill index is up to date');
} else if (next !== cur) {
  fs.writeFileSync(README, next);
  console.log(`README skill index updated (${skills.length} skills)`);
} else {
  console.log('README skill index already up to date');
}
